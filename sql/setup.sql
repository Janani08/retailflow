CREATE DATABASE IF NOT EXISTS RETAILFLOW_DB;

CREATE SCHEMA IF NOT EXISTS RETAILFLOW_DB.RAW;

CREATE SCHEMA IF NOT EXISTS RETAILFLOW_DB.DATA_VAULT;

CREATE SCHEMA IF NOT EXISTS RETAILFLOW_DB.ANALYTICS;

CREATE TABLE IF NOT EXISTS RETAILFLOW_DB.RAW.SALES (
    INVOICE VARCHAR,
    STOCK_CODE VARCHAR,
    DESCRIPTION VARCHAR,
    QUANTITY INTEGER,
    INVOICE_DATE TIMESTAMP_NTZ,
    PRICE NUMBER(12,2),
    CUSTOMER_ID VARCHAR,
    COUNTRY VARCHAR,
    SOURCE_YEAR VARCHAR
);

