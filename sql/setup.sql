CREATE TABLE IF NOT EXISTS RETAILFLOW_DB.RAW.SALES_INGEST_TEST
LIKE RETAILFLOW_DB.RAW.SALES;

CREATE TABLE IF NOT EXISTS RETAILFLOW_DB.RAW.INGESTION_LOG (
    FILE_NAME VARCHAR,
    FILE_HASH VARCHAR,
    ROW_COUNT INTEGER,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE FILE FORMAT IF NOT EXISTS
RETAILFLOW_DB.RAW.RETAIL_CSV_FORMAT
TYPE = CSV
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = TRUE
NULL_IF = ('')
TIMESTAMP_FORMAT = 'AUTO';

CREATE STAGE IF NOT EXISTS
RETAILFLOW_DB.RAW.RETAIL_STAGE
FILE_FORMAT = RETAILFLOW_DB.RAW.RETAIL_CSV_FORMAT;

COPY INTO RETAILFLOW_DB.RAW.SALES_INGEST_TEST
(
    INVOICE,
    STOCK_CODE,
    DESCRIPTION,
    QUANTITY,
    INVOICE_DATE,
    PRICE,
    CUSTOMER_ID,
    COUNTRY,
    SOURCE_YEAR
)
FROM (
    SELECT
        t.$1,
        t.$2,
        t.$3,
        t.$4,
        t.$5,
        t.$6,
        t.$7,
        t.$8,
        '2009-2010'
    FROM @RETAILFLOW_DB.RAW.RETAIL_STAGE/sales_2009_2010.csv.gz t
)
FILE_FORMAT = (
    FORMAT_NAME = 'RETAILFLOW_DB.RAW.RETAIL_CSV_FORMAT'
)
ON_ERROR = ABORT_STATEMENT;

SELECT
    COUNT(*) AS total_rows,
    COUNT(SOURCE_YEAR) AS rows_with_source_year
FROM RETAILFLOW_DB.RAW.SALES_INGEST_TEST;
